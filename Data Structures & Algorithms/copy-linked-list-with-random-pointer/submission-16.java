class Solution {
    public Node copyRandomList(Node head) {
        // use a hash map to linked the original node to its copied node
        Map<Node, Node> map = new HashMap<>();
        Node cur = head;
        while (cur != null) {
            map.put(cur, new Node(cur.val));
            cur = cur.next;
        }

        // copy the next and random now
        cur = head;
        while (cur != null) {
            // the next and random of the copied node is the copied node of the next and random of 
            // the original node
            map.get(cur).next = map.get(cur.next);
            map.get(cur).random = map.get(cur.random);
            cur = cur.next;
        }
        return map.get(head);
    }
}
